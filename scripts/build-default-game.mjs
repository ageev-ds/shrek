let seq = 0;
const nextId = (p) => `${p}-${(++seq).toString(36)}`;

function makeQuestion([text, answer, flags = ''], catIdx, lvlIdx) {
  const q = { id: nextId(`c${catIdx + 1}l${lvlIdx + 1}`), text, answer };
  for (const f of flags.split(',').map((s) => s.trim()).filter(Boolean)) {
    if (f === 'cat') q.catInBag = true;
    else if (f === 'x2') q.doubleStake = true;
    else if (f === 'auction') q.auction = true;
    else if (f === 'safe') q.noRisk = true;
    else if (f === 'verify') {
      q.verify = true;
      q.note = VERIFY_NOTE;
    } else if (f.startsWith('img:')) q.image = `builtin:${f.slice(4)}`;
    else throw new Error(`Неизвестный флаг ${f}`);
  }
  return q;
}

